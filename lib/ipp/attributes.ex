defmodule Hippy.IPP.Attributes do
  @moduledoc """
  Attribute definitions from the IANA IPP registry.

  Each attribute registered with IANA is described by a map:

    * `:types` - the value types it allows, as `{type, limit}`, e.g. `[{:integer, {1, :max}}]` for
      `copies`, or `[{:keyword, nil}, {:name, :max}]` for `media`. Types are `:integer`,
      `:boolean`, `:enum`, `:octet_string`, `:datetime`, `:resolution`, `:range_of_integer`,
      `:collection`, `:text`, `:name`, `:keyword`, `:uri`, `:uri_scheme`, `:charset`,
      `:natural_language`, `:mime_media_type`, `:no_value` and `:unknown`. A limit is `nil`, a
      maximum length (an integer or `:max`), or a `{min, max}` range.
    * `:set` - whether it can have several values (`1setOf` in the registry).
    * `:groups` - the groups it's registered in, e.g. `[:job_template, :document_template]`.
    * `:status` - `nil`, `:deprecated` or `:obsolete`.
    * `:members` - for collections, the member attributes by name, each described the same way
      (without `:groups`).

  Use a path, e.g. `get(["media-col", "media-size"])`, to look up nested members.

  The data is generated by `scripts/update_ipp_registry.exs` into `lib/ipp/attributes.eterm`,
  which is compiled in.
  """

  @path Path.expand("attributes.eterm", __DIR__)
  @external_resource @path

  {:ok, [{:updated, updated} | entries]} = :file.consult(@path)

  # The file leaves out fields with their default value.
  fill = fn fill, definition ->
    %{set: false, status: nil, members: %{}}
    |> Map.merge(definition)
    |> Map.update!(:members, &Map.new(&1, fn {name, member} -> {name, fill.(fill, member)} end))
  end

  @updated updated
  @attributes Map.new(entries, fn {name, definition} ->
                {name, Map.put_new(fill.(fill, definition), :groups, [])}
              end)

  @doc "The date the IANA registry was last updated, when the data was generated."
  def registry_updated, do: @updated

  @doc "The names of all registered attributes."
  def names, do: Map.keys(attributes())

  @doc """
  Returns the definition of an attribute, or `nil` if it isn't registered.

  Takes an attribute name, or a path to a collection member, e.g.
  `["media-col", "media-size", "x-dimension"]`.
  """
  def get(name) when is_binary(name), do: resolve(Map.get(attributes(), name))

  def get([name | members]) do
    Enum.reduce(members, get(name), fn
      member, %{members: members} -> resolve(Map.get(members, member))
      _member, nil -> nil
    end)
  end

  @doc "Returns whether an attribute (or member path) is registered."
  def known?(name), do: get(name) != nil

  @doc "Returns whether an attribute can have several values, or `nil` if it isn't registered."
  def set?(name), do: with(%{set: set} <- get(name), do: set)

  @doc "Returns the value types an attribute allows, or `nil` if it isn't registered."
  def types(name), do: with(%{types: types} <- get(name), do: types)

  @doc "Returns the groups an attribute is registered in, or `nil` if it isn't registered."
  def groups(name) when is_binary(name), do: with(%{groups: groups} <- get(name), do: groups)

  @doc """
  Returns the members of a collection attribute (or member path) by name, or `nil` if it isn't
  registered.
  """
  def members(name), do: with(%{members: members} <- get(name), do: members)

  # A collection registered as having the same members as another (e.g. media-col-actual and
  # media-col) refers to it with :like rather than repeating them. Its direct members are
  # resolved too, so `members/1` describes them fully.
  defp resolve(nil), do: nil

  defp resolve(definition) do
    definition
    |> resolve_like()
    |> Map.update!(:members, &Map.new(&1, fn {name, member} -> {name, resolve_like(member)} end))
  end

  defp resolve_like(%{like: base} = definition) do
    base_members =
      case Map.get(attributes(), base) do
        nil -> %{}
        base -> resolve_like(base).members
      end

    definition
    |> Map.delete(:like)
    |> Map.update!(:members, &Map.merge(base_members, &1))
  end

  defp resolve_like(definition), do: definition

  defp attributes, do: @attributes
end
